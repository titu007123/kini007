-- KINI007 Advanced Product Catalog + Video Ads
-- Run AFTER the existing supabase-admin-setup.sql.
-- Additive migration: does not delete or overwrite existing products.

begin;

alter table public.products
  add column if not exists subcategory text,
  add column if not exists sku text,
  add column if not exists video_url text,
  add column if not exists gallery_urls text[] not null default '{}',
  add column if not exists specifications jsonb not null default '{}'::jsonb,
  add column if not exists tags text[] not null default '{}',
  add column if not exists is_featured boolean not null default false,
  add column if not exists sort_order integer not null default 0;

create index if not exists products_category_active_idx
  on public.products (category, is_active, sort_order);
create index if not exists products_featured_idx
  on public.products (is_featured, is_active, sort_order);

create table if not exists public.product_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  parent_id bigint references public.product_categories(id) on delete set null,
  image_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.product_categories enable row level security;
grant select on public.product_categories to anon, authenticated;
grant insert, update, delete on public.product_categories to authenticated;
drop policy if exists "Public can view active product categories" on public.product_categories;
drop policy if exists "Admins manage product categories" on public.product_categories;
create policy "Public can view active product categories"
  on public.product_categories for select to anon, authenticated
  using (is_active = true or public.is_kini007_admin());
create policy "Admins manage product categories"
  on public.product_categories for all to authenticated
  using (public.is_kini007_admin()) with check (public.is_kini007_admin());

create table if not exists public.video_ads (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  media_type text not null default 'youtube'
    check (media_type in ('youtube','mp4')),
  video_url text not null,
  thumbnail_url text,
  placement text not null default 'homepage_hero'
    check (placement in ('homepage_hero','product_detail','promo_gallery')),
  product_id text,
  cta_label text not null default 'Shop Now',
  cta_url text,
  sort_order integer not null default 0,
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.video_ads enable row level security;
grant select on public.video_ads to anon, authenticated;
grant insert, update, delete on public.video_ads to authenticated;
drop policy if exists "Public can view scheduled active video ads" on public.video_ads;
drop policy if exists "Admins manage video ads" on public.video_ads;
create policy "Public can view scheduled active video ads"
  on public.video_ads for select to anon, authenticated
  using (
    is_active = true
    and (starts_at is null or starts_at <= now())
    and (ends_at is null or ends_at >= now())
  );
create policy "Admins manage video ads"
  on public.video_ads for all to authenticated
  using (public.is_kini007_admin()) with check (public.is_kini007_admin());

create index if not exists video_ads_placement_schedule_idx
  on public.video_ads (placement, is_active, sort_order, starts_at, ends_at);
create index if not exists product_categories_parent_sort_idx
  on public.product_categories (parent_id, sort_order);

-- Public media is required for public product images/videos.
-- Admin-only uploads/deletes; public visitors can read the published media.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'kini007-media',
  'kini007-media',
  true,
  104857600,
  array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm']
)
on conflict (id) do update set
  public = true,
  file_size_limit = 104857600,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can read Kini007 media" on storage.objects;
drop policy if exists "Admins upload Kini007 media" on storage.objects;
drop policy if exists "Admins update Kini007 media" on storage.objects;
drop policy if exists "Admins delete Kini007 media" on storage.objects;
create policy "Public can read Kini007 media"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'kini007-media');
create policy "Admins upload Kini007 media"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'kini007-media' and public.is_kini007_admin());
create policy "Admins update Kini007 media"
  on storage.objects for update to authenticated
  using (bucket_id = 'kini007-media' and public.is_kini007_admin())
  with check (bucket_id = 'kini007-media' and public.is_kini007_admin());
create policy "Admins delete Kini007 media"
  on storage.objects for delete to authenticated
  using (bucket_id = 'kini007-media' and public.is_kini007_admin());

grant usage, select on all sequences in schema public to authenticated;

commit;

