-- Kini007 Admin + Store Directory setup
-- Run this in Supabase SQL Editor as project owner.
-- First create the one admin user in Authentication > Users > Add user.
-- Then replace YOUR_AUTH_USER_UUID below and run the INSERT statement at the end.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
grant select on public.admin_users to authenticated;
drop policy if exists "Admin can read own allowlist row" on public.admin_users;
create policy "Admin can read own allowlist row"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

create or replace function public.is_kini007_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and is_active = true
  );
$$;
revoke all on function public.is_kini007_admin() from public;
grant execute on function public.is_kini007_admin() to authenticated;

-- Existing products table is retained. These policies grant write access only to allowlisted admins.
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
drop policy if exists "Kini007 admins can insert products" on public.products;
drop policy if exists "Kini007 admins can update products" on public.products;
drop policy if exists "Kini007 admins can delete products" on public.products;
create policy "Kini007 admins can insert products"
on public.products for insert to authenticated
with check (public.is_kini007_admin());
create policy "Kini007 admins can update products"
on public.products for update to authenticated
using (public.is_kini007_admin()) with check (public.is_kini007_admin());
create policy "Kini007 admins can delete products"
on public.products for delete to authenticated
using (public.is_kini007_admin());

create table if not exists public.stores (
  id bigint generated by default as identity primary key,
  name text not null,
  website_url text not null,
  integration_type text not null default 'manual'
    check (integration_type in ('manual','affiliate','csv','api')),
  affiliate_url text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.stores enable row level security;
grant select on public.stores to anon, authenticated;
grant insert, update, delete on public.stores to authenticated;
drop policy if exists "Public can view active stores" on public.stores;
drop policy if exists "Kini007 admins can manage stores" on public.stores;
create policy "Public can view active stores"
on public.stores for select to anon, authenticated
using (is_active = true or public.is_kini007_admin());
create policy "Kini007 admins can manage stores"
on public.stores for all to authenticated
using (public.is_kini007_admin()) with check (public.is_kini007_admin());

-- Identity sequence permission for inserting new products/stores.
grant usage, select on all sequences in schema public to authenticated;

